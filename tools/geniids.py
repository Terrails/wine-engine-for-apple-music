"""Write a C header listing every non-generic interface IID in the app's own metadata, so lab.exe
can probe an opaque object for the interfaces it answers to (see probe_iids() in dev/lab/lab.c).

usage: geniids.py <out.h> <winmd file or dir>...
  A directory contributes the AMP.*.winmd and Microsoft.UI.Xaml.winmd files in it (the app's own
  metadata, e.g. the installed app directory or the unpacked MSIX). The header is generated locally
  from that copy of the app and is not part of the repository.
"""
import glob, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wmd import Meta, TypeDef

if len(sys.argv) < 3:
    sys.exit(__doc__.strip())
out, inputs = sys.argv[1], sys.argv[2:]
files = []
for p in inputs:
    if os.path.isdir(p):
        files += sorted(glob.glob(os.path.join(p, 'AMP.*.winmd')))
        files += [f for f in [os.path.join(p, 'Microsoft.UI.Xaml.winmd')] if os.path.isfile(f)]
    else:
        files.append(p)
if not files:
    sys.exit('error: no .winmd files in ' + ' '.join(inputs))
metas = [Meta(f) for f in files]
rows = []
for m in metas:
    for name, idx in m.types.items():
        td = TypeDef(m, idx)
        if td.category not in ('interface', 'delegate') or td.generic_count or td.guid is None: continue
        b = td.guid.bytes
        rows.append('    {{0x%s,0x%s,0x%s,{%s}}, "%s"},' % (b[0:4].hex(), b[4:6].hex(), b[6:8].hex(),
                    ','.join('0x%02x' % x for x in b[8:]), name))
tmp = out + '.tmp'
with open(tmp, 'w') as f:
    f.write('/* generated by tools/geniids.py from the app\'s metadata; not part of the repository */\n'
            'static const struct { GUID iid; const char *name; } known_iids[] = {\n')
    f.write('\n'.join(sorted(set(rows))) + '\n};\n')
os.replace(tmp, out)
print(len(rows), 'interfaces')
